# Schema for raw LLM proposal prior to deterministic budget and date calculation
class BudgetProposalItem(BaseModel):
    """Raw proposed budget item with percentage."""

    key: str
    label: str
    percent: float
    note: str


class TaskProposalItem(BaseModel):
    """Raw proposed task with day offset relative to event date."""

    title: str
    phase: str
    offset_days: int
    owner: str
    status: Literal["todo", "doing", "done"]
    category_key: str


class PlanProposalV0(BaseModel):
    """Structured proposal generated by the LLM in single-call v0."""

    budget: list[BudgetProposalItem]
    timeline: list[TaskProposalItem]
    vendors: list[VendorItem]
    ideas: IdeaSet
    assumptions: list[str]


@dataclass
class GenerationResult:
    """Result of plan generation, including status, notices, and LLM telemetry."""

    plan: EventPlan
    is_fallback: bool
    notices: list[str]
    metadata: LLMMetadata | None = None
    provider: str | None = None


